"""Bronze layer: validate the raw dataset and write an immutable manifest.

Run:
    python -m src.data.make_bronze

Checks
------
1. ``data/meta.json`` exists and parses.
2. Every split folder exists and every image referenced by meta.json is present.
3. Every bbox is sane (xyxy, inside the image, non-degenerate).
4. Counts images/labels per split.

Writes ``data/_bronze_manifest.json`` — the contract everything downstream
relies on. If Silver later sees fewer annotations than the manifest promises,
it fails loudly instead of silently training on partial data.

Why this matters in an MLOps pipeline: CI and your laptop must agree about
what "the dataset" is. The manifest pins that down by content hash.
"""

from __future__ import annotations

import hashlib
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
CONFIG_PATH = PROJECT_ROOT / "configs" / "config.yaml"


def sha256(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while block := f.read(chunk):
            h.update(block)
    return h.hexdigest()


def load_meta(path: Path) -> dict:
    if not path.exists():
        raise SystemExit(
            f"[BRONZE] FAILED — {path} not found.\n"
            "Expected the synthetic dataset generated by the notebook:\n"
            "  data/meta.json\n"
            "  data/train/*.png  data/val/*.png  data/test/*.png"
        )
    try:
        meta = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit(f"[BRONZE] FAILED — meta.json is not valid JSON: {exc}")
    return meta


def check_split(meta: dict, split: str, img_root: Path, label_map: dict,
                problems: list[str]) -> dict:
    entries = meta.get(split, [])
    if not entries:
        problems.append(f"split '{split}' is missing or empty in meta.json")
        return {"images": 0, "annotations": 0, "labels": {}}

    split_dir = img_root / split
    if not split_dir.is_dir():
        problems.append(f"image folder missing: {split_dir}")
        return {"images": 0, "annotations": 0, "labels": {}}

    from PIL import Image

    n_ann = 0
    labels: Counter[str] = Counter()
    missing = bad_bbox = 0

    for entry in entries:
        file = entry.get("file")
        img_path = split_dir / file if file else None
        if img_path is None or not img_path.exists():
            missing += 1
            continue

        with Image.open(img_path) as im:
            iw, ih = im.size

        for ann in entry.get("annotations", []):
            bbox = ann.get("bbox")
            if not bbox or len(bbox) != 4:
                bad_bbox += 1
                continue
            x1, y1, x2, y2 = (float(v) for v in bbox)
            if x2 <= x1 or y2 <= y1:
                bad_bbox += 1
                continue
            if x1 < 0 or y1 < 0 or x2 > iw or y2 > ih:
                bad_bbox += 1
                continue

            lbl = ann.get("label")
            name = label_map.get(int(lbl)) if lbl is not None else None
            if name is None:
                bad_bbox += 1
                continue
            labels[name] += 1
            n_ann += 1

    if missing:
        problems.append(f"{split}: {missing} images referenced by meta.json not found")
    if bad_bbox:
        problems.append(f"{split}: {bad_bbox} malformed / out-of-bounds bboxes")

    return {"images": len(entries), "annotations": n_ann,
            "labels": dict(sorted(labels.items()))}


def main() -> int:
    cfg = yaml.safe_load(CONFIG_PATH.read_text(encoding="utf-8"))
    p, ds = cfg["paths"], cfg["dataset"]

    meta_path = PROJECT_ROOT / p["raw_meta"]
    img_root = PROJECT_ROOT / p["raw_images"]
    label_map = {int(k): v for k, v in ds["label_map"].items()}

    meta = load_meta(meta_path)

    problems: list[str] = []
    per_split = {
        s: check_split(meta, s, img_root, label_map, problems)
        for s in ds["splits"]
    }

    if problems:
        print("\n[BRONZE] FAILED — raw layer is inconsistent:\n")
        for msg in problems:
            print(f"  x {msg}")
        return 1

    manifest = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "source": "synthetic street-scene generator (notebook section 3)",
        "label_map": {str(k): v for k, v in label_map.items()},
        "splits": per_split,
        "meta_json_sha256": sha256(meta_path),
        "totals": {
            "images": sum(s["images"] for s in per_split.values()),
            "annotations": sum(s["annotations"] for s in per_split.values()),
        },
    }

    out = PROJECT_ROOT / p["bronze_manifest"]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    print("[BRONZE] OK")
    for split, info in per_split.items():
        print(f"  {split:5s}: {info['images']:4d} images, "
              f"{info['annotations']:4d} boxes  {info['labels']}")
    print(f"  total   : {manifest['totals']['images']} images, "
          f"{manifest['totals']['annotations']} boxes")
    print(f"  manifest -> {out.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
